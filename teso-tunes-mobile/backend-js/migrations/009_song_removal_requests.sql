-- Stage 3: durable, auditable artist-initiated 30-day song removal requests.
-- Additive only: no existing song, artist, agreement or verification data is removed.
begin;

do $$ begin
  if current_user in ('anon', 'authenticated', 'service_role') then
    raise exception 'Migration 009 requires a trusted database owner, not an API role';
  end if;
end $$;

alter table tesohub_music.songs
  add column if not exists removal_reason text not null default '',
  add column if not exists removed_at timestamptz;

create table if not exists tesohub_music.song_removal_requests (
  id bigint generated by default as identity primary key,
  song_id bigint references tesohub_music.songs(id) on delete set null,
  artist_id bigint references tesohub_music.artists(id) on delete set null,
  requested_by_listener_id bigint references tesohub_music.listeners(id) on delete set null,
  song_title text not null default '',
  reason text not null check (char_length(btrim(reason)) between 10 and 1000),
  status text not null default 'scheduled'
    check (status in ('scheduled', 'cancelled', 'completed')),
  requested_at timestamptz not null default now(),
  due_at timestamptz not null default (now() + interval '30 days'),
  cancellation_reason text not null default '',
  cancelled_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint song_removal_deadline_check check (due_at >= requested_at)
);

-- Keep this migration safe to re-run on staging environments where the
-- original preview was applied before cancellation evidence was added.
alter table tesohub_music.song_removal_requests
  add column if not exists cancellation_reason text not null default '';

do $$ begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'song_removal_cancellation_reason_check'
      and conrelid = 'tesohub_music.song_removal_requests'::regclass
  ) then
    alter table tesohub_music.song_removal_requests
      add constraint song_removal_cancellation_reason_check
      check (
        status <> 'cancelled'
        or char_length(btrim(cancellation_reason)) between 10 and 1000
      ) not valid;
  end if;
end $$;
alter table tesohub_music.song_removal_requests
  validate constraint song_removal_cancellation_reason_check;

-- One unfinished notice per song; old requests remain as historical records.
create unique index if not exists song_removal_one_scheduled_per_song_idx
  on tesohub_music.song_removal_requests (song_id) where status = 'scheduled';
create index if not exists song_removal_due_idx
  on tesohub_music.song_removal_requests (due_at, id) where status = 'scheduled';
create index if not exists song_removal_artist_idx
  on tesohub_music.song_removal_requests (artist_id, requested_at desc);

create table if not exists tesohub_music.song_removal_events (
  id bigint generated by default as identity primary key,
  request_id bigint not null references tesohub_music.song_removal_requests(id) on delete cascade,
  event_type text not null check (event_type in ('requested','cancelled','completed')),
  actor_type text not null check (actor_type in ('artist','admin','system')),
  actor_label text not null default '',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists song_removal_events_request_idx
  on tesohub_music.song_removal_events (request_id, id);

alter table tesohub_music.song_removal_requests enable row level security;
alter table tesohub_music.song_removal_events enable row level security;

do $$ begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'tesohub_music'
      and tablename = 'song_removal_requests'
      and policyname = 'song_removal_requests_client_deny'
  ) then
    create policy song_removal_requests_client_deny
      on tesohub_music.song_removal_requests as restrictive
      for all to public using (false) with check (false);
  end if;
  if not exists (
    select 1 from pg_policies
    where schemaname = 'tesohub_music'
      and tablename = 'song_removal_events'
      and policyname = 'song_removal_events_client_deny'
  ) then
    create policy song_removal_events_client_deny
      on tesohub_music.song_removal_events as restrictive
      for all to public using (false) with check (false);
  end if;
end $$;

revoke all on tesohub_music.song_removal_requests,
  tesohub_music.song_removal_events from public;
revoke all on sequence tesohub_music.song_removal_requests_id_seq,
  tesohub_music.song_removal_events_id_seq from public;

do $$ begin
  if exists(select 1 from pg_roles where rolname = 'anon') then
    revoke all on tesohub_music.song_removal_requests,
      tesohub_music.song_removal_events from anon;
    revoke all on sequence tesohub_music.song_removal_requests_id_seq,
      tesohub_music.song_removal_events_id_seq from anon;
  end if;
  if exists(select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on tesohub_music.song_removal_requests,
      tesohub_music.song_removal_events from authenticated;
    revoke all on sequence tesohub_music.song_removal_requests_id_seq,
      tesohub_music.song_removal_events_id_seq from authenticated;
  end if;
  if exists(select 1 from pg_roles where rolname = 'service_role') then
    revoke all on tesohub_music.song_removal_requests,
      tesohub_music.song_removal_events from service_role;
    revoke all on sequence tesohub_music.song_removal_requests_id_seq,
      tesohub_music.song_removal_events_id_seq from service_role;
  end if;
end $$;

-- This check is compatible with PostgreSQL 15 and 17. PostgreSQL 17's
-- MAINTAIN privilege is revoked above by REVOKE ALL, but is intentionally
-- omitted from the has_table_privilege list because PG15 cannot parse it.
-- Fail atomically when inherited membership still grants an API role access.
do $$ begin
  if exists (
    select 1
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    cross join pg_roles r
    where n.nspname = 'tesohub_music'
      and r.rolname in ('anon', 'authenticated', 'service_role')
      and case
        when c.relname in ('song_removal_requests', 'song_removal_events')
          and c.relkind = 'r'
          then has_table_privilege(
            r.oid,
            c.oid,
            'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER'
          )
        when c.relname in (
          'song_removal_requests_id_seq',
          'song_removal_events_id_seq'
        ) and c.relkind = 'S'
          then has_sequence_privilege(r.oid, c.oid, 'USAGE,SELECT,UPDATE')
        else false
      end
  ) then
    raise exception 'Migration 009: API role retains song-removal object privileges; inspect role memberships';
  end if;
end $$;

commit;
