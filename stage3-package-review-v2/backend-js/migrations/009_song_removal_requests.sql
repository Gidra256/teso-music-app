-- Stage 3: durable, auditable artist-initiated 30-day song removal requests.
-- Additive only: no existing song, artist, agreement or verification data is removed.
begin;

do $$ begin
  if current_user in ('anon', 'authenticated', 'service_role') then
    raise exception 'Migration 009 requires a trusted database owner, not an API role';
  end if;
end $$;

alter table tesohub_music.songs
  add column if not exists removal_reason text not null default '',
  add column if not exists removed_at timestamptz;

create table if not exists tesohub_music.song_removal_requests (
  id bigint generated by default as identity primary key,
  song_id bigint references tesohub_music.songs(id) on delete set null,
  artist_id bigint references tesohub_music.artists(id) on delete set null,
  requested_by_listener_id bigint references tesohub_music.listeners(id) on delete set null,
  song_title text not null default '',
  reason text not null check (char_length(btrim(reason)) between 10 and 1000),
  status text not null default 'scheduled'
    check (status in ('scheduled', 'cancelled', 'completed')),
  requested_at timestamptz not null default now(),
  due_at timestamptz not null default (now() + interval '30 days'),
  cancelled_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint song_removal_deadline_check check (due_at >= requested_at)
);

-- One unfinished notice per song; old requests remain as historical records.
create unique index if not exists song_removal_one_scheduled_per_song_idx
  on tesohub_music.song_removal_requests (song_id) where status = 'scheduled';
create index if not exists song_removal_due_idx
  on tesohub_music.song_removal_requests (due_at, id) where status = 'scheduled';
create index if not exists song_removal_artist_idx
  on tesohub_music.song_removal_requests (artist_id, requested_at desc);

create table if not exists tesohub_music.song_removal_events (
  id bigint generated by default as identity primary key,
  request_id bigint not null references tesohub_music.song_removal_requests(id) on delete cascade,
  event_type text not null check (event_type in ('requested','cancelled','completed')),
  actor_type text not null check (actor_type in ('artist','admin','system')),
  actor_label text not null default '',
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists song_removal_events_request_idx
  on tesohub_music.song_removal_events (request_id, id);

commit;
