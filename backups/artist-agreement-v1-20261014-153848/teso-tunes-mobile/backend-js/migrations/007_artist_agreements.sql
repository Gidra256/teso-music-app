-- One-shot atomic migration for versioned Artist Agreement acceptance.
-- The rollout mode defaults to off; this migration does not change any artist role.
begin;

do $$ begin
  if current_user in ('anon', 'authenticated', 'service_role') then
    raise exception 'Migration 007 requires a trusted database owner, not an API role';
  end if;
end $$;

create table tesohub_music.artist_agreement_versions (
  id bigint generated always as identity primary key,
  version text not null unique
    check (version = btrim(version) and length(version) between 1 and 80),
  title text not null
    check (title = btrim(title) and length(title) between 2 and 160),
  content_markdown text not null
    check (length(btrim(content_markdown)) >= 20),
  content_sha256 text not null
    check (content_sha256 ~ '^[0-9a-f]{64}$'),
  status text not null default 'draft'
    check (status in ('draft', 'published', 'retired')),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  check ((status = 'published' and published_at is not null) or status <> 'published')
);

-- There may be historical retired versions, but exactly zero or one current
-- published version. No agreement is inserted by this migration.
create unique index artist_agreement_one_published
  on tesohub_music.artist_agreement_versions ((status))
  where status = 'published';

create table tesohub_music.artist_agreement_acceptances (
  id bigint generated by default as identity primary key,
  agreement_version_id bigint not null
    references tesohub_music.artist_agreement_versions(id) on delete restrict,
  listener_id bigint not null
    references tesohub_music.listeners(id) on delete restrict,
  accepted_version text not null,
  content_sha256 text not null
    check (content_sha256 ~ '^[0-9a-f]{64}$'),
  accepted_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (listener_id, agreement_version_id)
);

create index artist_agreement_acceptance_listener
  on tesohub_music.artist_agreement_acceptances (listener_id, accepted_at desc);

alter table tesohub_music.artist_applications
  add column agreement_acceptance_id bigint
  references tesohub_music.artist_agreement_acceptances(id) on delete restrict
  deferrable initially deferred;

alter table tesohub_music.platform_settings
  add column artist_agreement_enforcement_mode text not null default 'off'
  check (artist_agreement_enforcement_mode in ('off', 'new_applications', 'all_artists'));

-- The database, not the client, supplies the acceptance evidence snapshot.
create function tesohub_music.prepare_artist_agreement_acceptance()
returns trigger
language plpgsql
set search_path = pg_catalog, tesohub_music
as $$
declare
  agreement tesohub_music.artist_agreement_versions%rowtype;
begin
  select * into agreement
  from tesohub_music.artist_agreement_versions
  where id = new.agreement_version_id
  for share;

  if agreement.id is null or agreement.status <> 'published' then
    raise exception 'Artist Agreement version is not currently published';
  end if;

  new.accepted_version := agreement.version;
  new.content_sha256 := agreement.content_sha256;
  new.accepted_at := clock_timestamp();
  new.created_at := new.accepted_at;
  return new;
end $$;

create trigger artist_agreement_acceptance_prepare
before insert on tesohub_music.artist_agreement_acceptances
for each row execute function tesohub_music.prepare_artist_agreement_acceptance();

create function tesohub_music.prevent_artist_agreement_evidence_mutation()
returns trigger
language plpgsql
set search_path = pg_catalog, tesohub_music
as $$
begin
  raise exception 'Artist Agreement acceptance records are immutable';
end $$;

create function tesohub_music.protect_artist_agreement_version()
returns trigger
language plpgsql
set search_path = pg_catalog, public, tesohub_music
as $$
declare
  calculated_hash text;
begin
  if tg_op = 'DELETE' then
    if old.status in ('published', 'retired') then
      raise exception 'Published or retired Artist Agreement versions cannot be deleted';
    end if;
    return old;
  end if;

  calculated_hash := encode(digest(convert_to(new.content_markdown, 'UTF8'), 'sha256'), 'hex');
  if new.content_sha256 <> calculated_hash then
    raise exception 'Artist Agreement content SHA-256 does not match its canonical content';
  end if;

  if tg_op = 'UPDATE' and old.status in ('published', 'retired') then
    if new.version is distinct from old.version
      or new.title is distinct from old.title
      or new.content_markdown is distinct from old.content_markdown
      or new.content_sha256 is distinct from old.content_sha256
      or new.published_at is distinct from old.published_at
      or new.created_at is distinct from old.created_at then
      raise exception 'Published or retired Artist Agreement evidence is immutable';
    end if;
    if old.status = 'retired' or new.status not in ('published', 'retired') then
      raise exception 'Artist Agreement status transition is not allowed';
    end if;
  end if;

  return new;
end $$;

create trigger artist_agreement_acceptance_immutable
before update or delete on tesohub_music.artist_agreement_acceptances
for each row execute function tesohub_music.prevent_artist_agreement_evidence_mutation();
create trigger artist_agreement_version_immutable
before insert or update or delete on tesohub_music.artist_agreement_versions
for each row execute function tesohub_music.protect_artist_agreement_version();

alter table tesohub_music.artist_agreement_versions enable row level security;
alter table tesohub_music.artist_agreement_acceptances enable row level security;
create policy artist_agreement_versions_client_deny
  on tesohub_music.artist_agreement_versions as restrictive
  for all to public using (false) with check (false);
create policy artist_agreement_acceptances_client_deny
  on tesohub_music.artist_agreement_acceptances as restrictive
  for all to public using (false) with check (false);

revoke all on tesohub_music.artist_agreement_versions,
  tesohub_music.artist_agreement_acceptances from public;
revoke all on sequence tesohub_music.artist_agreement_versions_id_seq,
  tesohub_music.artist_agreement_acceptances_id_seq from public;

do $$ begin
  if exists(select 1 from pg_roles where rolname = 'anon') then
    revoke all on tesohub_music.artist_agreement_versions,
      tesohub_music.artist_agreement_acceptances from anon;
    revoke all on sequence tesohub_music.artist_agreement_versions_id_seq,
      tesohub_music.artist_agreement_acceptances_id_seq from anon;
  end if;
  if exists(select 1 from pg_roles where rolname = 'authenticated') then
    revoke all on tesohub_music.artist_agreement_versions,
      tesohub_music.artist_agreement_acceptances from authenticated;
    revoke all on sequence tesohub_music.artist_agreement_versions_id_seq,
      tesohub_music.artist_agreement_acceptances_id_seq from authenticated;
  end if;
  if exists(select 1 from pg_roles where rolname = 'service_role') then
    revoke all on tesohub_music.artist_agreement_versions,
      tesohub_music.artist_agreement_acceptances from service_role;
    revoke all on sequence tesohub_music.artist_agreement_versions_id_seq,
      tesohub_music.artist_agreement_acceptances_id_seq from service_role;
  end if;
end $$;

-- Fail atomically if inherited role membership still confers client access.
do $$ begin
  if exists (
    select 1
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    cross join pg_roles r
    where n.nspname = 'tesohub_music'
      and r.rolname in ('anon', 'authenticated', 'service_role')
      and case
        when c.relname in ('artist_agreement_versions', 'artist_agreement_acceptances')
          and c.relkind = 'r'
          then has_table_privilege(
            r.oid,
            c.oid,
            'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER,MAINTAIN'
          )
        when c.relname in (
          'artist_agreement_versions_id_seq',
          'artist_agreement_acceptances_id_seq'
        ) and c.relkind = 'S'
          then has_sequence_privilege(r.oid, c.oid, 'USAGE,SELECT,UPDATE')
        else false
      end
  ) then
    raise exception 'Migration 007: API role retains Artist Agreement object privileges; inspect role memberships';
  end if;
end $$;

commit;
